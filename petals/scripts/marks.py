#!/usr/bin/env python3
"""The garden's marks: check the drawing rules, write the night files, print a tile.

A bed's mark is its drawing in one ink on a tile of its bloom, the way the site's plates carry a
bed's number: the bloom is the tile, the drawing is ink or paper, whichever the plate text uses.
The umbrella's own mark, and the mark of any bed with no row in colors.md's Product Accents table,
stay drawn in two inks with no tile: growth green and the bloom. The night file is derived from
the paper file through the tokens, never drawn by hand.

Everything comes from the brand folder, nothing is listed in this script:
  the beds          assets/<name>-mark.svg is the umbrella; products/<bed>/assets/<bed>-mark.svg
                    is a bed, each in a deterministic order (umbrella first, then by name)
  tiled or line     a bed with a row in colors.md's Product Accents table is tiled; the rest are
                    line marks. The table is read by its header: the product column is headed
                    Product, Tool or Name, the plate-text column "Plate text"
  the bloom         --pp-<bed> for a tiled bed; for a line mark, the token whose paper value is
                    the mark's colour besides growth green
  a tiled mark's ink  colors.md names plate text by word only, so this script maps it once:
                    ink -> the term-bg token, paper -> the term-text token
  the drawing rules DESIGN.md section 7: the grid ("A 24-unit square"), the line weight
                    ("Lines are 2 units"), the tile radius ("radius 5.5") and the drawing scale
                    ("scaled to 72 percent"); a rule it cannot read stops the run
  the tokens        tokens.css: paper is :root, night is :root overridden by [data-theme="dark"]

  python3 petals/scripts/marks.py [--brand DIR]            write every night file from its paper file
  python3 petals/scripts/marks.py [--brand DIR] --check    exit 1 if a mark breaks a rule or a night file drifted
  python3 petals/scripts/marks.py [--brand DIR] tile <bed> [--night]   print the mark on a tile, for favicons

Without --brand, the brand folder is the .brand of the nearest directory, walking up from the
current one, that holds .petalsrc or .brand/.
"""
import re
import sys
from collections import namedtuple
from pathlib import Path

GREEN = "primary"
# colors.md names a bloom's plate text by word only; these are the tokens those words mean
INK_TOKEN = {"ink": "term-bg", "paper": "term-text"}
NIGHT_NOTE = "<!-- generated by scripts/marks.py from the paper file; edit that one -->"

Bed = namedtuple("Bed", "name path plate")  # plate is None for a line mark
Rules = namedtuple("Rules", "grid stroke radius scale")
Plan = namedtuple("Plan", "bloom inks recolour")


class BrandError(Exception):
    """The brand folder does not say something this script needs."""


def find_brand(arg):
    """The brand folder: --brand, or the .brand of the nearest project root above the cwd."""
    if arg is not None:
        brand = Path(arg).resolve()
    else:
        here = Path.cwd().resolve()
        root = next((d for d in (here, *here.parents) if (d / ".petalsrc").is_file() or (d / ".brand").is_dir()), None)
        if root is None:
            raise BrandError("no project root found (no .petalsrc or .brand/ here or above); pass --brand DIR")
        brand = root / ".brand"
    if not brand.is_dir():
        raise BrandError(f"no brand folder at {brand}")
    return brand


def read_file(path, brand):
    try:
        return path.read_text()
    except OSError:
        raise BrandError(f"cannot read {path.relative_to(brand.parent)}")


def tokens(brand):
    """Paper and night values of every --pp-* colour, read from tokens.css."""
    css = read_file(brand / "tokens.css", brand)
    if '[data-theme="dark"]' not in css:
        raise BrandError('tokens.css has no [data-theme="dark"] block')
    root, dark = css.split('[data-theme="dark"]', 1)
    pick = lambda block: dict(re.findall(r"--pp-([a-z0-9-]+):\s*(#[0-9A-Fa-f]{6})", block))
    paper = pick(root)
    night = {**paper, **pick(dark)}
    return paper, night


def design_rules(brand):
    """The drawing rules, parsed from DESIGN.md section 7."""
    text = read_file(brand / "DESIGN.md", brand)
    section = re.search(r"^## 7\..*?(?=^## |\Z)", text, re.M | re.S)
    if not section:
        raise BrandError('DESIGN.md has no "## 7." section to read the drawing rules from')
    body = section.group(0)
    found = {}
    for key, pattern, quote in (
        ("grid", r"A\s+(\d+)-unit\s+square", "A 24-unit square"),
        ("stroke", r"Lines\s+are\s+([0-9.]+)\s+units", "Lines are 2 units"),
        ("radius", r"radius\s+([0-9.]+)", "radius 5.5"),
        ("scale", r"scaled\s+to\s+([0-9.]+)\s+percent", "scaled to 72 percent"),
    ):
        m = re.search(pattern, body)
        if not m:
            raise BrandError(f'DESIGN.md section 7 does not say the {key} (expected wording like "{quote}")')
        found[key] = m.group(1)
    return Rules(**found)


def accents(brand):
    """Product Accents table of colors.md: tool name -> plate text word."""
    lines = read_file(brand / "colors.md", brand).splitlines()
    heading = next((i for i, l in enumerate(lines) if re.match(r"#+\s+Product Accents\b", l)), None)
    if heading is None:
        raise BrandError('colors.md has no "Product Accents" section')
    table = []
    for l in lines[heading + 1:]:
        if l.startswith("#"):
            break
        if l.lstrip().startswith("|"):
            table.append([c.strip().strip("`").strip() for c in l.strip().strip("|").split("|")])
        elif table:
            break
    if not table:
        raise BrandError("colors.md: the Product Accents section has no table")
    header = [c.lower() for c in table[0]]
    name_col = next((header.index(h) for h in ("product", "tool", "name") if h in header), None)
    if name_col is None:
        raise BrandError("colors.md: the Product Accents table has no Product, Tool or Name column")
    if "plate text" not in header:
        raise BrandError('colors.md: the Product Accents table has no "Plate text" column')
    plate_col = header.index("plate text")
    rows = {}
    for r in table[1:]:
        if len(r) > max(name_col, plate_col) and not set("".join(r)) <= set("-: "):
            rows[r[name_col].lower()] = r[plate_col].lower()
    return rows


def find_beds(brand, plates):
    """The umbrella's mark, then every product layer with a mark, in name order."""
    umbrella = sorted((brand / "assets").glob("*-mark.svg"))
    if len(umbrella) != 1:
        raise BrandError(f"expected one assets/<name>-mark.svg in the brand folder, found {len(umbrella)}")
    beds = [Bed(umbrella[0].name[: -len("-mark.svg")], umbrella[0], None)]
    products = brand / "products"
    for d in sorted(products.iterdir()) if products.is_dir() else []:
        mark = d / "assets" / f"{d.name}-mark.svg"
        if mark.is_file():
            beds.append(Bed(d.name, mark, plates.get(d.name)))
    return beds


def night_path(bed):
    return bed.path.with_name(bed.path.stem + "-night.svg")


def hexes(svg):
    return {c.upper() for c in re.findall(r"#[0-9A-Fa-f]{6}", svg)}


def plan(bed, svg, paper):
    """Which tokens colour this mark: (Plan or None, problems that stop the other checks)."""
    if bed.plate is not None:
        ink = INK_TOKEN.get(bed.plate)
        if ink is None:
            return None, [f'its plate text "{bed.plate}" in colors.md is neither ink nor paper']
        missing = [t for t in (bed.name, ink) if t not in paper]
        if missing:
            return None, [f"tokens.css has no --pp-{t}" for t in missing]
        return Plan(bed.name, (bed.name, ink), (bed.name,)), []
    if GREEN not in paper:
        return None, [f"tokens.css has no --pp-{GREEN}"]
    others = hexes(svg) - {paper[GREEN].upper()}
    if len(others) != 1:
        shown = ", ".join(sorted(others)) or "none"
        return None, [f"cannot tell its bloom: the colours besides growth green are {shown}, and a line mark has exactly one"]
    (colour,) = others
    named = sorted(n for n, v in paper.items() if v.upper() == colour and n != GREEN)
    if bed.name in named:
        named = [bed.name]
    if len(named) != 1:
        which = "no token has" if not named else f"tokens {', '.join(named)} all have"
        return None, [f"cannot tell its bloom: {which} the mark's colour {colour}"]
    return Plan(named[0], (GREEN, named[0]), (GREEN, named[0])), []


def to_night(svg, plan_, paper, night):
    out = svg
    for name in plan_.recolour:
        out = re.sub(re.escape(paper[name]), night[name], out, flags=re.I)
    return out.replace("\n", "\n  " + NIGHT_NOTE + "\n", 1)


def problems(bed, svg, paper, plan_, rules):
    found = []
    if f'viewBox="0 0 {rules.grid} {rules.grid}"' not in svg:
        found.append(f"viewBox is not 0 0 {rules.grid} {rules.grid}")
    extra = hexes(svg) - {paper[t].upper() for t in plan_.inks}
    if extra:
        found.append(f"inks outside {'green and the accent' if bed.plate is None else 'the tile and its ink'}: {', '.join(sorted(extra))}")
    widths = set(re.findall(r'stroke-width="([0-9.]+)"', svg))
    if widths - {rules.stroke}:
        found.append(f"stroke widths other than {rules.stroke}: {', '.join(sorted(widths - {rules.stroke}))}")
    rects = re.findall(r"<rect\b[^>]*>", svg)
    if bed.plate is None:
        if rects:
            found.append("a tile is baked in; tiles come from `marks.py tile`")
        return found
    tile = f'<rect width="{rules.grid}" height="{rules.grid}" rx="{rules.radius}" fill="{paper[plan_.bloom]}"/>'
    if len(rects) != 1 or rects[0].upper() != tile.upper():
        found.append(f"the tile is not {tile}")
    elif svg.upper().index("<RECT") > min(svg.upper().find(t) for t in ("<PATH", "<CIRCLE", "<G") if t in svg.upper()):
        found.append("the tile is not drawn first")
    return found


def tile(bed, svg, plan_, paper, night, rules, night_mode):
    if night_mode:
        svg = to_night(svg, plan_, paper, night)
    if bed.plate is not None:
        return svg
    inner = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    inner = re.sub(r"^\s*<svg[^>]*>|</svg>\s*$", "", inner.strip(), flags=re.S).strip()
    ground = (night if night_mode else paper)["bg" if night_mode else "surface"]
    grid = rules.grid
    scale = float(rules.scale) / 100
    offset = round(int(grid) / 2 * (1 - scale), 2)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {grid} {grid}" role="img" aria-label="{bed.name}">\n'
        f'  <rect width="{grid}" height="{grid}" rx="{rules.radius}" fill="{ground}"/>\n'
        f'  <g transform="translate({offset} {offset}) scale({scale})" fill="none" '
        f'stroke-linecap="round" stroke-linejoin="round">\n    {inner}\n  </g>\n</svg>\n'
    )


def split_brand(argv):
    """(brand argument or None, remaining argv); a --brand without a value is left in argv."""
    if "--brand" in argv:
        i = argv.index("--brand")
        if i + 1 < len(argv):
            return argv[i + 1], argv[:i] + argv[i + 2:]
    return None, argv


def run(argv):
    brand_arg, argv = split_brand(argv)
    check = argv == ["--check"]
    want_tile = argv[:1] == ["tile"] and len(argv) >= 2
    if "--brand" in argv or (argv and not check and not want_tile):
        sys.stderr.write(__doc__)
        return 2
    brand = find_brand(brand_arg)
    root = brand.parent
    paper, night = tokens(brand)
    rules = design_rules(brand)
    plates = accents(brand)
    beds = find_beds(brand, plates)
    if want_tile:
        bed = next((b for b in beds if b.name == argv[1]), None)
        if bed is None:
            sys.stderr.write(__doc__)
            return 2
        svg = read_file(bed.path, brand)
        plan_, stopped = plan(bed, svg, paper)
        if stopped:
            raise BrandError(f"{bed.name}: {stopped[0]}")
        sys.stdout.write(tile(bed, svg, plan_, paper, night, rules, "--night" in argv))
        return 0
    failed = False
    for bed in beds:
        svg = read_file(bed.path, brand)
        plan_, found = plan(bed, svg, paper)
        if plan_ is not None:
            found = problems(bed, svg, paper, plan_, rules)
        for p in found:
            print(f"{bed.name}: {p}")
            failed = True
        if plan_ is None:
            continue
        want = to_night(svg, plan_, paper, night)
        dst = night_path(bed)
        if check:
            if not dst.exists() or dst.read_text() != want:
                print(f"{bed.name}: {dst.relative_to(root)} is not derived from the paper file; run scripts/marks.py")
                failed = True
        else:
            dst.write_text(want)
    if check and not failed:
        print(f"marks: {len(beds)} beds, rules hold, night files derived")
    return 1 if failed else 0


def main(argv):
    try:
        return run(argv)
    except BrandError as e:
        sys.stderr.write(f"marks: {e}\n")
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
