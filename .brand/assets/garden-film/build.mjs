// Wrap embed.html (the one home of the film's code) into the standalone garden.html.
// Run: node build.mjs
import fs from 'node:fs';

const here = (f) => new URL(f, import.meta.url);
const src = fs.readFileSync(here('./embed.html'), 'utf8');
const pick = (re, what) => { const m = src.match(re); if (!m) throw Error('embed.html has no ' + what); return m[0]; };
const style = pick(/^<style>[\s\S]*?^<\/style>/m, 'style block');
const section = pick(/^<section class="pp-film"[\s\S]*?^<\/section>/m, 'film section');
const script = pick(/^<script>[\s\S]*?^<\/script>/m, 'script block');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>plotplot · the garden film</title>
<link rel="icon" href="data:,">
<!-- generated by build.mjs from embed.html; edit embed.html, then rebuild -->
${style}
<style>
html,body{margin:0;background:#F2EAD6;color:#3A2718;font:16px/1.5 system-ui,sans-serif}
.bar{display:flex;gap:16px;align-items:center;padding:12px 16px}
.bar button{font:inherit;background:#FAF5E9;color:#3A2718;border:1px solid #E2D8C0;border-radius:6px;padding:4px 12px;cursor:pointer}
.bar output{font-variant-numeric:tabular-nums;color:#786148}
.show-quiet .pp-film-stage::after{content:"";position:absolute;left:0;top:0;width:45%;height:55%;outline:1px dashed #D6502F;outline-offset:-1px;pointer-events:none}
</style>
</head>
<body>
${section}
<div class="bar"><button id="toggle" type="button">Pause</button><button id="quiet" type="button">Show quiet zone</button><output id="clock">0.0 s</output></div>
${script}
<script>
(() => {
  const root = document.querySelector('.pp-film'), api = root.__film;
  const q = new URLSearchParams(location.search);
  window.__riso = {
    duration: api.duration,
    get ready() { return api.ready; },
    seek: (t) => api.seek(t),
    shots: api.shots,
    still: api.still,
  };
  const btn = document.getElementById('toggle'), clock = document.getElementById('clock');
  btn.onclick = () => { if (api.playing) api.pause(); else api.play(); };
  document.getElementById('quiet').onclick = () => root.classList.toggle('show-quiet');
  if (q.has('t')) api.seek(Number(q.get('t')));
  if (q.has('paused')) api.pause();
  setInterval(() => { btn.textContent = api.playing ? 'Pause' : 'Play'; const c = api.cost(); clock.textContent = c.length ? 'frame ' + (c.reduce((a, b) => a + b, 0) / c.length).toFixed(1) + ' ms' : ''; }, 250);
})();
</script>
</body>
</html>
`;
fs.writeFileSync(here('./garden.html'), html);
console.log('wrote garden.html');
